    id   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL UNIQUE
);

CREATE TABLE sessions (
    id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    day_id      INTEGER NOT NULL REFERENCES days(id),
    start_time  TIME NOT NULL,
    end_time    TIME NOT NULL,
    title       TEXT NOT NULL,
    track_id    INTEGER REFERENCES tracks(id),
    level       TEXT,
    format      TEXT NOT NULL,
    location_id INTEGER NOT NULL REFERENCES locations(id),
    notes       TEXT,
    CHECK (end_time >= start_time)
);
CREATE INDEX sessions_day_start_idx ON sessions (day_id, start_time);
CREATE INDEX sessions_track_idx ON sessions (track_id);
CREATE INDEX sessions_format_idx ON sessions (format);

CREATE TABLE session_speakers (
    session_id INTEGER NOT NULL REFERENCES sessions(id) ON DELETE CASCADE,
    speaker_id INTEGER NOT NULL REFERENCES speakers(id),
    PRIMARY KEY (session_id, speaker_id)
);
CREATE INDEX session_speakers_speaker_idx ON session_speakers (speaker_id);

